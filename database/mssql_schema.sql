-- =====================================================================================
-- STORED PROCEDURE: TÍNH LÃI LỖ P&L (PROFIT & LOSS STATEMENT)
-- =====================================================================================
CREATE OR ALTER PROCEDURE sp_BaoCaoLaiLo
    @TuNgay DATETIME2,
    @DenNgay DATETIME2
AS
BEGIN
    SET NOCOUNT ON;

    -- 1. TỔNG DOANH THU BÁN HÀNG
    DECLARE @DoanhThuBanHang DECIMAL(18,2) = 0;
    SELECT @DoanhThuBanHang = ISNULL(SUM(TienMatThucThu), 0)
    FROM HOA_DON_BAN_HANG
    WHERE TrangThaiThanhToan = N'DaThanhToan'
      AND NgayGioLap BETWEEN @TuNgay AND @DenNgay;

    -- 2. TỔNG GIÁ VỐN HÀNG BÁN (COGS - DỰA TRÊN ĐỊNH MỨC NGUYÊN VẬT LIỆU * ĐƠN GIÁ BÌNH QUÂN)
    DECLARE @GiaVonHangBan DECIMAL(18,2) = 0;
    SELECT @GiaVonHangBan = ISNULL(SUM(ct.SoLuong * ctm.SoLuongDinhMuc * vt.DonGiaBinhQuan), 0)
    FROM HOA_DON_BAN_HANG hd
    JOIN CHI_TIET_HOA_DON ct ON hd.SoHoaDon = ct.SoHoaDon
    JOIN CONG_THUC_MON ctm ON ct.MaMon = ctm.MaMon
    JOIN VAT_TU_NGUYEN_LIEU vt ON ctm.MaVatTu = vt.MaVatTu
    WHERE hd.TrangThaiThanhToan = N'DaThanhToan'
      AND hd.NgayGioLap BETWEEN @TuNgay AND @DenNgay;

    -- 3. HAO HỤT / HỦY KHO
    DECLARE @ChiPhiHaoHut DECIMAL(18,2) = 0;
    SELECT @ChiPhiHaoHut = ISNULL(SUM(TongGiaTriHaoHut), 0)
    FROM PHIEU_HUY_HAO_HUT
    WHERE NgayHuy BETWEEN @TuNgay AND @DenNgay;

    -- 4. TỔNG THU KHÁC (TỪ SỔ QUỸ)
    DECLARE @ThuKhac DECIMAL(18,2) = 0;
    SELECT @ThuKhac = ISNULL(SUM(SoTien), 0)
    FROM SO_QUY_THU_CHI
    WHERE LoaiPhieu = N'Thu'
      AND ChungTuGoc NOT LIKE 'HD%' -- Trừ thu từ bán hàng đã tính ở mục 1
      AND NgayPhatSinh BETWEEN @TuNgay AND @DenNgay;

    -- 5. CHI PHÍ VẬN HÀNH (ĐIỆN, NƯỚC, MẶT BẰNG, VẬT DỤNG TIÊU HAO...)
    DECLARE @ChiPhiVanHanh DECIMAL(18,2) = 0;
    SELECT @ChiPhiVanHanh = ISNULL(SUM(SoTien), 0)
    FROM SO_QUY_THU_CHI
    WHERE LoaiPhieu = N'Chi'
      AND ChungTuGoc NOT LIKE 'PN%' -- Trừ chi nhập hàng đã kết chuyển vào tồn kho/giá vốn
      AND NgayPhatSinh BETWEEN @TuNgay AND @DenNgay;

    -- 6. CHI PHÍ LƯƠNG NHÂN VIÊN
    DECLARE @ChiPhiLuong DECIMAL(18,2) = 0;
    SELECT @ChiPhiLuong = ISNULL(SUM(ThucLinh), 0)
    FROM BANG_THANH_TOAN_LUONG
    WHERE NgayTinhLuong BETWEEN @TuNgay AND @DenNgay;

    -- TÍNH TOÁN CÁC CHỈ SỐ P&L
    DECLARE @LoiNhuanGop DECIMAL(18,2) = @DoanhThuBanHang - @GiaVonHangBan;
    DECLARE @TongChiPhiHoatDong DECIMAL(18,2) = @ChiPhiVanHanh + @ChiPhiLuong + @ChiPhiHaoHut;
    DECLARE @LoiNhuanRong DECIMAL(18,2) = @LoiNhuanGop + @ThuKhac - @TongChiPhiHoatDong;

    SELECT 
        @DoanhThuBanHang AS DoanhThuBanHang,
        @GiaVonHangBan AS GiaVonHangBan_COGS,
        @LoiNhuanGop AS LoiNhuanGop,
        @ThuKhac AS ThuKhac,
        @ChiPhiVanHanh AS ChiPhiVanHanh,
        @ChiPhiLuong AS ChiPhiLuong,
        @ChiPhiHaoHut AS ChiPhiHaoHut,
        @TongChiPhiHoatDong AS TongChiPhiHoatDong,
        @LoiNhuanRong AS LoiNhuanRong_NetProfit;
END;
GO
