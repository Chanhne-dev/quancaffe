    ThoiGianDuyet DATETIME2 NULL,
    TrangThaiDuyet NVARCHAR(30) NOT NULL DEFAULT N'ChoDuyet', -- ChoDuyet / DaDuyet / TuChoi
    CONSTRAINT PK_YEU_CAU_HUY_DOI_MON PRIMARY KEY (MaYeuCau),
    CONSTRAINT FK_HUY_MON_HOA_DON FOREIGN KEY (SoHoaDon) REFERENCES HOA_DON_BAN_HANG(SoHoaDon),
