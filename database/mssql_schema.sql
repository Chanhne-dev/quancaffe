-- 11. BẢNG DANH MỤC MÓN
CREATE TABLE DANH_MUC_MON (
    MaMon NVARCHAR(30) NOT NULL,
    TenMon NVARCHAR(150) NOT NULL,
    MaNhom NVARCHAR(20) NOT NULL,
    DonViTinh NVARCHAR(30) NOT NULL DEFAULT N'Ly',
    GiaBanHienHanh DECIMAL(18, 2) NOT NULL,
    HinhAnh NVARCHAR(500) NULL,
    DangKinhDoanh BIT NOT NULL DEFAULT 1,
    CONSTRAINT PK_DANH_MUC_MON PRIMARY KEY (MaMon),
    CONSTRAINT FK_DANH_MUC_MON_NHOM FOREIGN KEY (MaNhom) REFERENCES NHOM_MON(MaNhom),
    CONSTRAINT CHK_GiaBan CHECK (GiaBanHienHanh >= 0)
);

-- 17. BẢNG NHÀ CUNG CẤP (TẠO TRƯỚC VÌ ĐƯỢC THAM CHIẾU BỞI VẬT TƯ NGUYÊN LIỆU/PHIẾU NHẬP)
CREATE TABLE NHA_CUNG_CAP (
    MaNCC NVARCHAR(20) NOT NULL,
    TenNCC NVARCHAR(200) NOT NULL,
    SoDienThoai NVARCHAR(20) NULL,
    DiaChi NVARCHAR(255) NULL,
    CongNoHienTai DECIMAL(18, 2) NOT NULL DEFAULT 0,
