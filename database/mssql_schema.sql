-- 1. BẢNG ĐƠN VỊ BỘ PHẬN
CREATE TABLE DON_VI_BO_PHAN (
    MaBoPhan NVARCHAR(20) NOT NULL,
    TenBoPhan NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_DON_VI_BO_PHAN PRIMARY KEY (MaBoPhan)
);

-- 2. BẢNG CHỨC VỤ
CREATE TABLE CHUC_VU (
    MaChucVu NVARCHAR(20) NOT NULL,
    TenChucVu NVARCHAR(100) NOT NULL,
    HeSoLuong DECIMAL(5, 2) NOT NULL DEFAULT 1.00,
    CONSTRAINT PK_CHUC_VU PRIMARY KEY (MaChucVu),
    CONSTRAINT CHK_HeSoLuong CHECK (HeSoLuong > 0)
);

-- 3. BẢNG NHÂN VIÊN
CREATE TABLE NHAN_VIEN (
    MaNhanVien NVARCHAR(20) NOT NULL,
    HoTen NVARCHAR(150) NOT NULL,
    NgaySinh DATE NULL,
    SoDienThoai NVARCHAR(20) NOT NULL,
    MaChucVu NVARCHAR(20) NOT NULL,
    MaBoPhan NVARCHAR(20) NOT NULL,
    TrangThaiLamViec NVARCHAR(30) NOT NULL DEFAULT N'DangLamViec', -- DangLamViec / NghiPhep / DaNghiViec
    NgayTao DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_NHAN_VIEN PRIMARY KEY (MaNhanVien),
    CONSTRAINT FK_NHAN_VIEN_CHUC_VU FOREIGN KEY (MaChucVu) REFERENCES CHUC_VU(MaChucVu),
    CONSTRAINT FK_NHAN_VIEN_BO_PHAN FOREIGN KEY (MaBoPhan) REFERENCES DON_VI_BO_PHAN(MaBoPhan)
);

-- 4. BẢNG TÀI KHOẢN & PHÂN QUYỀN (RBAC - 5 VAI TRÒ)
CREATE TABLE TAI_KHOAN (
    MaTaiKhoan NVARCHAR(20) NOT NULL,
    MaNhanVien NVARCHAR(20) NOT NULL,
    TenDangNhap NVARCHAR(50) NOT NULL,
    MatKhauHash NVARCHAR(255) NOT NULL,
    VaiTro NVARCHAR(30) NOT NULL, -- ChuQuan / QuanLy / ThuNgan / PhaChe / PhucVu
    KichHoat BIT NOT NULL DEFAULT 1,
    CONSTRAINT PK_TAI_KHOAN PRIMARY KEY (MaTaiKhoan),
    CONSTRAINT UQ_TAI_KHOAN_TenDangNhap UNIQUE (TenDangNhap),
    CONSTRAINT FK_TAI_KHOAN_NHAN_VIEN FOREIGN KEY (MaNhanVien) REFERENCES NHAN_VIEN(MaNhanVien) ON DELETE CASCADE,
    CONSTRAINT CHK_VaiTro CHECK (VaiTro IN (N'ChuQuan', N'QuanLy', N'ThuNgan', N'PhaChe', N'PhucVu'))
);

-- 5. BẢNG CA LÀM VIỆC
CREATE TABLE CA_LAM_VIEC (
    MaCa NVARCHAR(20) NOT NULL,
    TenCa NVARCHAR(100) NOT NULL,
    GioBatDau TIME(0) NOT NULL,
    GioKetThuc TIME(0) NOT NULL,
    TienCongTheoCa DECIMAL(18, 2) NOT NULL DEFAULT 0,
    CONSTRAINT PK_CA_LAM_VIEC PRIMARY KEY (MaCa)
);

-- 6. BẢNG KÊ GIAO CA (CASH DRAWER BALANCING)
CREATE TABLE BANG_KE_GIAO_CA (
    MaGiaoCa NVARCHAR(30) NOT NULL,
    MaCa NVARCHAR(20) NOT NULL,
    MaNhanVien NVARCHAR(20) NOT NULL,
    NgayLamViec DATE NOT NULL,
    ThoiGianMoCa DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    ThoiGianDongCa DATETIME2 NULL,
    TienDauCa DECIMAL(18, 2) NOT NULL DEFAULT 0,
    DoanhThuTienMat DECIMAL(18, 2) NOT NULL DEFAULT 0,
    DoanhThuChuyenKhoan DECIMAL(18, 2) NOT NULL DEFAULT 0,
    TienMatThucTeTrongKet DECIMAL(18, 2) NOT NULL DEFAULT 0,
    ChenhLechThuaThieu DECIMAL(18, 2) NOT NULL DEFAULT 0, -- TienMatThucTeTrongKet - (TienDauCa + DoanhThuTienMat)
    TrangThai NVARCHAR(30) NOT NULL DEFAULT N'DangMo', -- DangMo / DaChot / DaXacNhan
    NguoiXacNhan NVARCHAR(20) NULL,
    GhiChuGiaoCa NVARCHAR(500) NULL,
    CONSTRAINT PK_BANG_KE_GIAO_CA PRIMARY KEY (MaGiaoCa),
    CONSTRAINT FK_GIAO_CA_CA_LAM FOREIGN KEY (MaCa) REFERENCES CA_LAM_VIEC(MaCa),
    CONSTRAINT FK_GIAO_CA_NHAN_VIEN FOREIGN KEY (MaNhanVien) REFERENCES NHAN_VIEN(MaNhanVien),
    CONSTRAINT FK_GIAO_CA_NGUOI_XAC_NHAN FOREIGN KEY (NguoiXacNhan) REFERENCES NHAN_VIEN(MaNhanVien)
);

-- 7. BẢNG THANH TOÁN LƯƠNG
CREATE TABLE BANG_THANH_TOAN_LUONG (
    MaBangLuong NVARCHAR(30) NOT NULL,
    ThangNam NVARCHAR(7) NOT NULL, -- Format YYYY-MM
    MaNhanVien NVARCHAR(20) NOT NULL,
    TongGioLam DECIMAL(7, 2) NOT NULL DEFAULT 0,
    LuongCoBan DECIMAL(18, 2) NOT NULL DEFAULT 0,
    Thuong DECIMAL(18, 2) NOT NULL DEFAULT 0,
    Phat DECIMAL(18, 2) NOT NULL DEFAULT 0,
    ThucLinh AS (LuongCoBan + Thuong - Phat) PERSISTED,
    NgayTinhLuong DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    TrangThai NVARCHAR(30) NOT NULL DEFAULT N'ChuaThanhToan',
    CONSTRAINT PK_BANG_THANH_TOAN_LUONG PRIMARY KEY (MaBangLuong),
    CONSTRAINT FK_LUONG_NHAN_VIEN FOREIGN KEY (MaNhanVien) REFERENCES NHAN_VIEN(MaNhanVien)
);

