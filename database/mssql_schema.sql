-- 18. BẢNG VẬT TƯ NGUYÊN LIỆU
CREATE TABLE VAT_TU_NGUYEN_LIEU (
    MaVatTu NVARCHAR(30) NOT NULL,
    TenVatTu NVARCHAR(150) NOT NULL,
    DonViTinh NVARCHAR(30) NOT NULL, -- g, ml, hop, goi, kg, lit
    SoLuongTonHienTai DECIMAL(12, 3) NOT NULL DEFAULT 0,
    MucToiThieuCanCanhBao DECIMAL(12, 3) NOT NULL DEFAULT 10,
    DonGiaBinhQuan DECIMAL(18, 2) NOT NULL DEFAULT 0,
    CONSTRAINT PK_VAT_TU_NGUYEN_LIEU PRIMARY KEY (MaVatTu),
    CONSTRAINT CHK_MucToiThieu CHECK (MucToiThieuCanCanhBao >= 0)
);

-- 12. BẢNG CÔNG THỨC MÓN (RECIPE MAPPING)
CREATE TABLE CONG_THUC_MON (
    MaCongThuc NVARCHAR(30) NOT NULL,
    MaMon NVARCHAR(30) NOT NULL,
    MaVatTu NVARCHAR(30) NOT NULL,
    SoLuongDinhMuc DECIMAL(10, 3) NOT NULL,
    DonViTinh NVARCHAR(30) NOT NULL,
    GhiChu NVARCHAR(255) NULL,
    CONSTRAINT PK_CONG_THUC_MON PRIMARY KEY (MaCongThuc),
    CONSTRAINT FK_CONG_THUC_MON FOREIGN KEY (MaMon) REFERENCES DANH_MUC_MON(MaMon) ON DELETE CASCADE,
    CONSTRAINT FK_CONG_THUC_VAT_TU FOREIGN KEY (MaVatTu) REFERENCES VAT_TU_NGUYEN_LIEU(MaVatTu),
    CONSTRAINT CHK_SoLuongDinhMuc CHECK (SoLuongDinhMuc > 0)
);

