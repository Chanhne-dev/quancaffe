    TenBan NVARCHAR(100) NOT NULL,
    MaKhuVuc NVARCHAR(20) NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL DEFAULT N'Trong', -- Trong / CoKhach / DatTruoc
    SoGhe INT NOT NULL DEFAULT 4,
    CONSTRAINT PK_BAN PRIMARY KEY (MaBan),
    CONSTRAINT FK_BAN_KHU_VUC FOREIGN KEY (MaKhuVuc) REFERENCES KHU_VUC(MaKhuVuc),
