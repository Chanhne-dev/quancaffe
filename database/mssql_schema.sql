-- 14. BẢNG HÓA ĐƠN BÁN HÀNG
CREATE TABLE HOA_DON_BAN_HANG (
    SoHoaDon NVARCHAR(35) NOT NULL,
    NgayGioLap DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    KenhDatHang NVARCHAR(30) NOT NULL DEFAULT N'TaiBan', -- TaiBan / MangDi / GiaoHang
    MaBan NVARCHAR(20) NULL,
    MaNhanVien NVARCHAR(20) NOT NULL,
    MaKhachHang NVARCHAR(20) NULL,
    TongTienMon DECIMAL(18, 2) NOT NULL DEFAULT 0,
    GiamGia DECIMAL(18, 2) NOT NULL DEFAULT 0,
    TienMatThucThu DECIMAL(18, 2) NOT NULL DEFAULT 0,
    PhuongThucThanhToan NVARCHAR(30) NOT NULL DEFAULT N'TienMat', -- TienMat / QR / The / MoMo / VNPay
    TrangThaiThanhToan NVARCHAR(30) NOT NULL DEFAULT N'ChoThanhToan', -- ChoThanhToan / DaThanhToan / DaHuy
    MaCa NVARCHAR(20) NULL,
    GhiChu NVARCHAR(255) NULL,
    OfflineId NVARCHAR(50) NULL, -- Phục vụ Reconciliation khi chạy Offline Mode
    DaDongBo BIT NOT NULL DEFAULT 1,
    CONSTRAINT PK_HOA_DON_BAN_HANG PRIMARY KEY (SoHoaDon),
    CONSTRAINT FK_HOA_DON_BAN FOREIGN KEY (MaBan) REFERENCES BAN(MaBan),
    CONSTRAINT FK_HOA_DON_NHAN_VIEN FOREIGN KEY (MaNhanVien) REFERENCES NHAN_VIEN(MaNhanVien),
    CONSTRAINT FK_HOA_DON_KHACH_HANG FOREIGN KEY (MaKhachHang) REFERENCES KHACH_HANG(MaKhachHang),
    CONSTRAINT FK_HOA_DON_CA FOREIGN KEY (MaCa) REFERENCES CA_LAM_VIEC(MaCa),
    CONSTRAINT CHK_KenhDatHang CHECK (KenhDatHang IN (N'TaiBan', N'MangDi', N'GiaoHang')),
    CONSTRAINT CHK_TrangThaiThanhToan CHECK (TrangThaiThanhToan IN (N'ChoThanhToan', N'DaThanhToan', N'DaHuy'))
);

-- 15. BẢNG CHI TIẾT HÓA ĐƠN
CREATE TABLE CHI_TIET_HOA_DON (
    MaChiTiet BIGINT IDENTITY(1,1) NOT NULL,
    SoHoaDon NVARCHAR(35) NOT NULL,
    MaMon NVARCHAR(30) NOT NULL,
    SoLuong INT NOT NULL DEFAULT 1,
    DonGia DECIMAL(18, 2) NOT NULL,
    ThanhTien AS (SoLuong * DonGia) PERSISTED,
    GhiChuTopping NVARCHAR(255) NULL, -- Ví dụ: '50% đường, ít đá, Trân châu đen'
    TrangThaiPhaChe NVARCHAR(30) NOT NULL DEFAULT N'ChoLam', -- ChoLam / DangLam / HoanThanh
    ThoiGianGuiBep DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    ThoiGianHoanThanh DATETIME2 NULL,
    CONSTRAINT PK_CHI_TIET_HOA_DON PRIMARY KEY (MaChiTiet),
    CONSTRAINT FK_CTHD_HOA_DON FOREIGN KEY (SoHoaDon) REFERENCES HOA_DON_BAN_HANG(SoHoaDon) ON DELETE CASCADE,
    CONSTRAINT FK_CTHD_MON FOREIGN KEY (MaMon) REFERENCES DANH_MUC_MON(MaMon),
    CONSTRAINT CHK_CTHD_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CHK_TrangThaiPhaChe CHECK (TrangThaiPhaChe IN (N'ChoLam', N'DangLam', N'HoanThanh'))
);

-- 16. BẢNG YÊU CẦU HỦY / ĐỔI MÓN
CREATE TABLE YEU_CAU_HUY_DOI_MON (
