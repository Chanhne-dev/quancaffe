-- =====================================================================================
-- HỆ THỐNG QUẢN LÝ QUÁN CÀ PHÊ (F&B POS SYSTEM)
-- DATABASE SCHEMA DEFINITION FOR POSTGRESQL (14+)
-- 23 CORE TABLES WITH CONSTRAINTS, INDEXES, AND AUTO-DEDUCTION TRIGGER
-- =====================================================================================

-- 1. ĐƠN VỊ BỘ PHẬN
CREATE TABLE IF NOT EXISTS DON_VI_BO_PHAN (
    MaBoPhan VARCHAR(20) PRIMARY KEY,
    TenBoPhan VARCHAR(100) NOT NULL
);

-- 2. CHỨC VỤ
CREATE TABLE IF NOT EXISTS CHUC_VU (
    MaChucVu VARCHAR(20) PRIMARY KEY,
    TenChucVu VARCHAR(100) NOT NULL,
    HeSoLuong NUMERIC(5, 2) NOT NULL DEFAULT 1.00 CHECK (HeSoLuong > 0)
);

-- 3. NHÂN VIÊN
CREATE TABLE IF NOT EXISTS NHAN_VIEN (
    MaNhanVien VARCHAR(20) PRIMARY KEY,
    HoTen VARCHAR(150) NOT NULL,
    NgaySinh DATE,
    SoDienThoai VARCHAR(20) NOT NULL,
    MaChucVu VARCHAR(20) NOT NULL REFERENCES CHUC_VU(MaChucVu),
    MaBoPhan VARCHAR(20) NOT NULL REFERENCES DON_VI_BO_PHAN(MaBoPhan),
    TrangThaiLamViec VARCHAR(30) NOT NULL DEFAULT 'DangLamViec',
    NgayTao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. TÀI KHOẢN (5 VAI TRÒ RBAC)
CREATE TABLE IF NOT EXISTS TAI_KHOAN (
    MaTaiKhoan VARCHAR(20) PRIMARY KEY,
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien) ON DELETE CASCADE,
    TenDangNhap VARCHAR(50) UNIQUE NOT NULL,
    MatKhauHash VARCHAR(255) NOT NULL,
    VaiTro VARCHAR(30) NOT NULL CHECK (VaiTro IN ('ChuQuan', 'QuanLy', 'ThuNgan', 'PhaChe', 'PhucVu')),
    KichHoat BOOLEAN NOT NULL DEFAULT TRUE
);

-- 5. CA LÀM VIỆC
CREATE TABLE IF NOT EXISTS CA_LAM_VIEC (
    MaCa VARCHAR(20) PRIMARY KEY,
    TenCa VARCHAR(100) NOT NULL,
    GioBatDau TIME NOT NULL,
    GioKetThuc TIME NOT NULL,
    TienCongTheoCa NUMERIC(18, 2) NOT NULL DEFAULT 0
);

-- 6. BẢNG KÊ GIAO CA (CASH DRAWER BALANCING)
CREATE TABLE IF NOT EXISTS BANG_KE_GIAO_CA (
    MaGiaoCa VARCHAR(30) PRIMARY KEY,
    MaCa VARCHAR(20) NOT NULL REFERENCES CA_LAM_VIEC(MaCa),
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    NgayLamViec DATE NOT NULL,
    ThoiGianMoCa TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ThoiGianDongCa TIMESTAMPTZ,
    TienDauCa NUMERIC(18, 2) NOT NULL DEFAULT 0,
    DoanhThuTienMat NUMERIC(18, 2) NOT NULL DEFAULT 0,
    DoanhThuChuyenKhoan NUMERIC(18, 2) NOT NULL DEFAULT 0,
    TienMatThucTeTrongKet NUMERIC(18, 2) NOT NULL DEFAULT 0,
    ChenhLechThuaThieu NUMERIC(18, 2) NOT NULL DEFAULT 0,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'DangMo',
    NguoiXacNhan VARCHAR(20) REFERENCES NHAN_VIEN(MaNhanVien),
    GhiChuGiaoCa TEXT
);

-- 7. BẢNG THANH TOÁN LƯƠNG
CREATE TABLE IF NOT EXISTS BANG_THANH_TOAN_LUONG (
    MaBangLuong VARCHAR(30) PRIMARY KEY,
    ThangNam VARCHAR(7) NOT NULL,
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    TongGioLam NUMERIC(7, 2) NOT NULL DEFAULT 0,
    LuongCoBan NUMERIC(18, 2) NOT NULL DEFAULT 0,
    Thuong NUMERIC(18, 2) NOT NULL DEFAULT 0,
    Phat NUMERIC(18, 2) NOT NULL DEFAULT 0,
    ThucLinh NUMERIC(18, 2) GENERATED ALWAYS AS (LuongCoBan + Thuong - Phat) STORED,
    NgayTinhLuong TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'ChuaThanhToan'
);

-- 8. KHU VỰC
CREATE TABLE IF NOT EXISTS KHU_VUC (
    MaKhuVuc VARCHAR(20) PRIMARY KEY,
    TenKhuVuc VARCHAR(100) NOT NULL
);

-- 9. BÀN
CREATE TABLE IF NOT EXISTS BAN (
    MaBan VARCHAR(20) PRIMARY KEY,
    TenBan VARCHAR(100) NOT NULL,
    MaKhuVuc VARCHAR(20) NOT NULL REFERENCES KHU_VUC(MaKhuVuc),
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Trong' CHECK (TrangThai IN ('Trong', 'CoKhach', 'DatTruoc')),
    SoGhe INT NOT NULL DEFAULT 4
);

-- 10. NHÓM MÓN
CREATE TABLE IF NOT EXISTS NHOM_MON (
    MaNhom VARCHAR(20) PRIMARY KEY,
    TenNhom VARCHAR(100) NOT NULL,
    ThuTuHienThi INT NOT NULL DEFAULT 0
);

-- 11. DANH MỤC MÓN
CREATE TABLE IF NOT EXISTS DANH_MUC_MON (
    MaMon VARCHAR(30) PRIMARY KEY,
    TenMon VARCHAR(150) NOT NULL,
    MaNhom VARCHAR(20) NOT NULL REFERENCES NHOM_MON(MaNhom),
    DonViTinh VARCHAR(30) NOT NULL DEFAULT 'Ly',
    GiaBanHienHanh NUMERIC(18, 2) NOT NULL CHECK (GiaBanHienHanh >= 0),
    HinhAnh VARCHAR(500),
    DangKinhDoanh BOOLEAN NOT NULL DEFAULT TRUE
);

-- 17. NHÀ CUNG CẤP
CREATE TABLE IF NOT EXISTS NHA_CUNG_CAP (
    MaNCC VARCHAR(20) PRIMARY KEY,
    TenNCC VARCHAR(200) NOT NULL,
    SoDienThoai VARCHAR(20),
    DiaChi VARCHAR(255),
    CongNoHienTai NUMERIC(18, 2) NOT NULL DEFAULT 0
);

-- 18. VẬT TƯ NGUYÊN LIỆU
CREATE TABLE IF NOT EXISTS VAT_TU_NGUYEN_LIEU (
    MaVatTu VARCHAR(30) PRIMARY KEY,
    TenVatTu VARCHAR(150) NOT NULL,
    DonViTinh VARCHAR(30) NOT NULL,
    SoLuongTonHienTai NUMERIC(12, 3) NOT NULL DEFAULT 0,
    MucToiThieuCanCanhBao NUMERIC(12, 3) NOT NULL DEFAULT 10 CHECK (MucToiThieuCanCanhBao >= 0),
    DonGiaBinhQuan NUMERIC(18, 2) NOT NULL DEFAULT 0
);

-- 12. CÔNG THỨC MÓN
CREATE TABLE IF NOT EXISTS CONG_THUC_MON (
    MaCongThuc VARCHAR(30) PRIMARY KEY,
    MaMon VARCHAR(30) NOT NULL REFERENCES DANH_MUC_MON(MaMon) ON DELETE CASCADE,
    MaVatTu VARCHAR(30) NOT NULL REFERENCES VAT_TU_NGUYEN_LIEU(MaVatTu),
    SoLuongDinhMuc NUMERIC(10, 3) NOT NULL CHECK (SoLuongDinhMuc > 0),
    DonViTinh VARCHAR(30) NOT NULL,
    GhiChu VARCHAR(255)
);

-- 13. KHÁCH HÀNG
CREATE TABLE IF NOT EXISTS KHACH_HANG (
    MaKhachHang VARCHAR(20) PRIMARY KEY,
    HoTen VARCHAR(150) NOT NULL,
    SoDienThoai VARCHAR(20) UNIQUE NOT NULL,
    DiemTichLuy INT NOT NULL DEFAULT 0,
    HangThanhVien VARCHAR(30) NOT NULL DEFAULT 'Member' CHECK (HangThanhVien IN ('Member', 'Silver', 'Gold', 'VIP')),
    NgayDangKy TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 14. HÓA ĐƠN BÁN HÀNG
CREATE TABLE IF NOT EXISTS HOA_DON_BAN_HANG (
    SoHoaDon VARCHAR(35) PRIMARY KEY,
    NgayGioLap TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KenhDatHang VARCHAR(30) NOT NULL DEFAULT 'TaiBan' CHECK (KenhDatHang IN ('TaiBan', 'MangDi', 'GiaoHang')),
    MaBan VARCHAR(20) REFERENCES BAN(MaBan),
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    MaKhachHang VARCHAR(20) REFERENCES KHACH_HANG(MaKhachHang),
    TongTienMon NUMERIC(18, 2) NOT NULL DEFAULT 0,
    GiamGia NUMERIC(18, 2) NOT NULL DEFAULT 0,
    TienMatThucThu NUMERIC(18, 2) NOT NULL DEFAULT 0,
    PhuongThucThanhToan VARCHAR(30) NOT NULL DEFAULT 'TienMat',
    TrangThaiThanhToan VARCHAR(30) NOT NULL DEFAULT 'ChoThanhToan' CHECK (TrangThaiThanhToan IN ('ChoThanhToan', 'DaThanhToan', 'DaHuy')),
    MaCa VARCHAR(20) REFERENCES CA_LAM_VIEC(MaCa),
    GhiChu VARCHAR(255),
    OfflineId VARCHAR(50),
    DaDongBo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 15. CHI TIẾT HÓA ĐƠN
CREATE TABLE IF NOT EXISTS CHI_TIET_HOA_DON (
    MaChiTiet BIGSERIAL PRIMARY KEY,
    SoHoaDon VARCHAR(35) NOT NULL REFERENCES HOA_DON_BAN_HANG(SoHoaDon) ON DELETE CASCADE,
    MaMon VARCHAR(30) NOT NULL REFERENCES DANH_MUC_MON(MaMon),
    SoLuong INT NOT NULL DEFAULT 1 CHECK (SoLuong > 0),
    DonGia NUMERIC(18, 2) NOT NULL,
    ThanhTien NUMERIC(18, 2) GENERATED ALWAYS AS (SoLuong * DonGia) STORED,
    GhiChuTopping VARCHAR(255),
    TrangThaiPhaChe VARCHAR(30) NOT NULL DEFAULT 'ChoLam' CHECK (TrangThaiPhaChe IN ('ChoLam', 'DangLam', 'HoanThanh')),
    ThoiGianGuiBep TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ThoiGianHoanThanh TIMESTAMPTZ
);

-- 16. YÊU CẦU HỦY ĐỔI MÓN
CREATE TABLE IF NOT EXISTS YEU_CAU_HUY_DOI_MON (
    MaYeuCau VARCHAR(35) PRIMARY KEY,
    SoHoaDon VARCHAR(35) NOT NULL REFERENCES HOA_DON_BAN_HANG(SoHoaDon),
    MaChiTiet BIGINT NOT NULL REFERENCES CHI_TIET_HOA_DON(MaChiTiet),
    LyDoHuy VARCHAR(255) NOT NULL,
    NguoiYeuCau VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    NguoiPheDuyet VARCHAR(20) REFERENCES NHAN_VIEN(MaNhanVien),
    ThoiGianYeuCau TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ThoiGianDuyet TIMESTAMPTZ,
    TrangThaiDuyet VARCHAR(30) NOT NULL DEFAULT 'ChoDuyet'
);

-- 19. PHIẾU NHẬP KHO
CREATE TABLE IF NOT EXISTS PHIEU_NHAP_KHO (
    SoPhieuNhap VARCHAR(35) PRIMARY KEY,
    NgayNhap TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MaNCC VARCHAR(20) NOT NULL REFERENCES NHA_CUNG_CAP(MaNCC),
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    TongTienNhap NUMERIC(18, 2) NOT NULL DEFAULT 0,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'DaNhap',
    GhiChu VARCHAR(255)
);

-- 20. CHI TIẾT PHIẾU NHẬP
CREATE TABLE IF NOT EXISTS CHI_TIET_PHIEU_NHAP (
    MaCTNhap BIGSERIAL PRIMARY KEY,
    SoPhieuNhap VARCHAR(35) NOT NULL REFERENCES PHIEU_NHAP_KHO(SoPhieuNhap) ON DELETE CASCADE,
    MaVatTu VARCHAR(30) NOT NULL REFERENCES VAT_TU_NGUYEN_LIEU(MaVatTu),
    SoLuongNhap NUMERIC(12, 3) NOT NULL CHECK (SoLuongNhap > 0),
    DonGiaNhap NUMERIC(18, 2) NOT NULL,
    ThanhTien NUMERIC(18, 2) GENERATED ALWAYS AS (SoLuongNhap * DonGiaNhap) STORED
);

-- 21. PHIẾU HỦY HAO HỤT
CREATE TABLE IF NOT EXISTS PHIEU_HUY_HAO_HUT (
    SoPhieuHuy VARCHAR(35) PRIMARY KEY,
    NgayHuy TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    TongGiaTriHaoHut NUMERIC(18, 2) NOT NULL DEFAULT 0,
    LyDoHaoHut VARCHAR(255) NOT NULL
);

-- 22. CHI TIẾT HỦY HAO HỤT
CREATE TABLE IF NOT EXISTS CHI_TIET_HUY_HAO_HUT (
    MaCTHuy BIGSERIAL PRIMARY KEY,
    SoPhieuHuy VARCHAR(35) NOT NULL REFERENCES PHIEU_HUY_HAO_HUT(SoPhieuHuy) ON DELETE CASCADE,
    MaVatTu VARCHAR(30) NOT NULL REFERENCES VAT_TU_NGUYEN_LIEU(MaVatTu),
    SoLuongHaoHut NUMERIC(12, 3) NOT NULL CHECK (SoLuongHaoHut > 0),
    GiaTri NUMERIC(18, 2) NOT NULL
);

-- 23. SỔ QUỸ THU CHI
CREATE TABLE IF NOT EXISTS SO_QUY_THU_CHI (
    MaPhieuThuChi VARCHAR(35) PRIMARY KEY,
    LoaiPhieu VARCHAR(10) NOT NULL CHECK (LoaiPhieu IN ('Thu', 'Chi')),
    NgayPhatSinh TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    SoTien NUMERIC(18, 2) NOT NULL CHECK (SoTien > 0),
    MaNhanVien VARCHAR(20) NOT NULL REFERENCES NHAN_VIEN(MaNhanVien),
    DoiTuongNopNhan VARCHAR(150),
    ChungTuGoc VARCHAR(50),
    LyDo VARCHAR(255) NOT NULL
);

-- INDEXES
CREATE INDEX IF NOT EXISTS IX_HOA_DON_NgayGioLap ON HOA_DON_BAN_HANG(NgayGioLap DESC);
CREATE INDEX IF NOT EXISTS IX_CHI_TIET_SoHoaDon ON CHI_TIET_HOA_DON(SoHoaDon);
CREATE INDEX IF NOT EXISTS IX_CONG_THUC_MaMon ON CONG_THUC_MON(MaMon);
CREATE INDEX IF NOT EXISTS IX_VAT_TU_TonKho ON VAT_TU_NGUYEN_LIEU(SoLuongTonHienTai);
